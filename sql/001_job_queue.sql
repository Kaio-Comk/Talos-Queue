-- pg-lease-queue: a durable job queue for Postgres / Supabase.
--
-- Guarantees
--   * at most ONE active job per (kind, dedupe_key): enqueueing the same work twice
--     returns the existing job;
--   * lease + FOR UPDATE SKIP LOCKED: several workers never take the same job, and a
--     job whose worker crashed is recovered when its lease expires;
--   * retries with backoff and an attempts cap;
--   * anon/authenticated can neither read nor call anything: use the service role.
--
-- Run it in staging first. It contains no secrets.

CREATE TABLE IF NOT EXISTS public.job_queue (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind              text   NOT NULL CHECK (length(trim(kind)) > 0),
    dedupe_key        text   NOT NULL CHECK (length(trim(dedupe_key)) > 0),
    payload           jsonb  NOT NULL DEFAULT '{}'::jsonb,
    status            text   NOT NULL DEFAULT 'queued'
                      CHECK (status IN ('queued', 'running', 'retry_wait', 'completed', 'failed')),
    stage             text,                               -- free text: 'downloading', 'uploading'...
    priority          smallint NOT NULL DEFAULT 100 CHECK (priority BETWEEN 0 AND 1000),  -- lower runs first
    attempts          integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at   timestamptz NOT NULL DEFAULT now(),
    lease_owner       text,
    lease_expires_at  timestamptz,
    last_error        text,
    result            jsonb,
    created_at        timestamptz NOT NULL DEFAULT now(),
    started_at        timestamptz,
    completed_at      timestamptz,
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT job_queue_lease_check CHECK (
        (lease_owner IS NULL AND lease_expires_at IS NULL)
        OR (lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL)
    )
);

-- Deduplicates ACTIVE work only; completed/failed rows stay as history.
CREATE UNIQUE INDEX IF NOT EXISTS ux_job_queue_active
    ON public.job_queue (kind, dedupe_key)
    WHERE status IN ('queued', 'running', 'retry_wait');

CREATE INDEX IF NOT EXISTS idx_job_queue_claim
    ON public.job_queue (priority, next_attempt_at, created_at)
    WHERE status IN ('queued', 'retry_wait');

CREATE INDEX IF NOT EXISTS idx_job_queue_expired_lease
    ON public.job_queue (lease_expires_at)
    WHERE status = 'running';

CREATE OR REPLACE FUNCTION public.job_queue_touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_job_queue_touch ON public.job_queue;
CREATE TRIGGER trg_job_queue_touch
    BEFORE UPDATE ON public.job_queue
    FOR EACH ROW EXECUTE FUNCTION public.job_queue_touch_updated_at();

-- Enqueue: returns the existing active job when there is one (payload is NOT replaced).
CREATE OR REPLACE FUNCTION public.enqueue_job(
    p_kind text,
    p_dedupe_key text,
    p_payload jsonb DEFAULT '{}'::jsonb,
    p_priority smallint DEFAULT 100
)
RETURNS public.job_queue
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_job public.job_queue;
BEGIN
    IF coalesce(length(trim(p_kind)), 0) = 0
       OR coalesce(length(trim(p_dedupe_key)), 0) = 0
       OR p_priority IS NULL OR p_priority < 0 OR p_priority > 1000 THEN
        RAISE EXCEPTION 'invalid enqueue_job parameters' USING ERRCODE = '22023';
    END IF;

    INSERT INTO public.job_queue (kind, dedupe_key, payload, priority)
    VALUES (p_kind, p_dedupe_key, coalesce(p_payload, '{}'::jsonb), p_priority)
    ON CONFLICT (kind, dedupe_key)
        WHERE status IN ('queued', 'running', 'retry_wait')
    DO UPDATE SET updated_at = now()
    RETURNING * INTO v_job;

    RETURN v_job;
END;
$$;

-- Claim one eligible job (optionally of one kind). Expired leases are recovered
-- in place. Returns an all-NULL row when there is nothing to do.
CREATE OR REPLACE FUNCTION public.claim_job(
    p_worker_id text,
    p_kind text DEFAULT NULL,
    p_lease_seconds integer DEFAULT 300
)
RETURNS public.job_queue
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_job public.job_queue;
BEGIN
    IF coalesce(length(trim(p_worker_id)), 0) = 0
       OR p_lease_seconds < 30 OR p_lease_seconds > 3600 THEN
        RAISE EXCEPTION 'invalid worker/lease' USING ERRCODE = '22023';
    END IF;

    WITH candidate AS (
        SELECT id
        FROM public.job_queue
        WHERE (p_kind IS NULL OR kind = p_kind)
          AND (
                (status IN ('queued', 'retry_wait') AND next_attempt_at <= now())
             OR (status = 'running' AND lease_expires_at < now())
          )
        ORDER BY priority ASC, next_attempt_at ASC, created_at ASC
        FOR UPDATE SKIP LOCKED
        LIMIT 1
    )
    UPDATE public.job_queue AS j
       SET status = 'running',
           lease_owner = p_worker_id,
           lease_expires_at = now() + make_interval(secs => p_lease_seconds),
           started_at = coalesce(j.started_at, now()),
           attempts = j.attempts + 1,
           last_error = CASE
               WHEN j.status = 'running' AND j.lease_expires_at < now()
               THEN 'previous lease expired; job recovered'
               ELSE j.last_error
           END
      FROM candidate
     WHERE j.id = candidate.id
     RETURNING j.* INTO v_job;

    RETURN v_job;
END;
$$;

-- Extend the lease. Returns false when the worker no longer owns the job.
CREATE OR REPLACE FUNCTION public.heartbeat_job(
    p_job_id bigint,
    p_worker_id text,
    p_lease_seconds integer DEFAULT 300
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    IF p_job_id IS NULL OR p_job_id <= 0
       OR coalesce(length(trim(p_worker_id)), 0) = 0
       OR p_lease_seconds < 30 OR p_lease_seconds > 3600 THEN
        RAISE EXCEPTION 'invalid heartbeat' USING ERRCODE = '22023';
    END IF;

    UPDATE public.job_queue
       SET lease_expires_at = now() + make_interval(secs => p_lease_seconds)
     WHERE id = p_job_id AND lease_owner = p_worker_id AND status = 'running';
    RETURN FOUND;
END;
$$;

-- Record the current stage (and renew the lease) while the worker still owns the job.
CREATE OR REPLACE FUNCTION public.set_job_stage(
    p_job_id bigint,
    p_worker_id text,
    p_stage text,
    p_lease_seconds integer DEFAULT 300
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    IF p_job_id IS NULL OR p_job_id <= 0
       OR coalesce(length(trim(p_worker_id)), 0) = 0
       OR p_lease_seconds < 30 OR p_lease_seconds > 3600 THEN
        RAISE EXCEPTION 'invalid stage update' USING ERRCODE = '22023';
    END IF;

    UPDATE public.job_queue
       SET stage = left(p_stage, 100),
           lease_expires_at = now() + make_interval(secs => p_lease_seconds)
     WHERE id = p_job_id AND lease_owner = p_worker_id AND status = 'running';
    RETURN FOUND;
END;
$$;

-- Complete the job and release the lease.
CREATE OR REPLACE FUNCTION public.finish_job(
    p_job_id bigint,
    p_worker_id text,
    p_result jsonb DEFAULT NULL
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    IF p_job_id IS NULL OR p_job_id <= 0
       OR coalesce(length(trim(p_worker_id)), 0) = 0 THEN
        RAISE EXCEPTION 'invalid finish' USING ERRCODE = '22023';
    END IF;

    UPDATE public.job_queue
       SET status = 'completed',
           result = p_result,
           completed_at = now(),
           lease_owner = NULL,
           lease_expires_at = NULL,
           last_error = NULL
     WHERE id = p_job_id AND lease_owner = p_worker_id AND status = 'running';
    RETURN FOUND;
END;
$$;

-- Failure: permanent, or retry with backoff. Past p_max_attempts a retry becomes a
-- permanent failure. Always releases the lease.
CREATE OR REPLACE FUNCTION public.fail_job(
    p_job_id bigint,
    p_worker_id text,
    p_error text,
    p_retry boolean DEFAULT false,
    p_retry_seconds integer DEFAULT 60,
    p_max_attempts integer DEFAULT 5
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    IF p_job_id IS NULL OR p_job_id <= 0
       OR coalesce(length(trim(p_worker_id)), 0) = 0
       OR p_retry_seconds < 5 OR p_retry_seconds > 86400
       OR p_max_attempts < 1 THEN
        RAISE EXCEPTION 'invalid failure' USING ERRCODE = '22023';
    END IF;

    UPDATE public.job_queue
       SET status = CASE WHEN p_retry AND attempts < p_max_attempts
                         THEN 'retry_wait' ELSE 'failed' END,
           last_error = left(coalesce(p_error, 'unknown error'), 500),
           next_attempt_at = CASE
               WHEN p_retry AND attempts < p_max_attempts
               THEN now() + make_interval(secs => p_retry_seconds)
               ELSE next_attempt_at
           END,
           completed_at = CASE WHEN p_retry AND attempts < p_max_attempts
                               THEN NULL ELSE now() END,
           lease_owner = NULL,
           lease_expires_at = NULL
     WHERE id = p_job_id AND lease_owner = p_worker_id AND status = 'running';
    RETURN FOUND;
END;
$$;

-- Only the service role may touch the queue.
